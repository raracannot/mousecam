const base = "http://127.0.0.1:9222";
const ts = await (await fetch(`${base}/json`)).json();
const p = ts.find(t => t.type === "page" && !t.url.startsWith("devtools://"));
const ws = new WebSocket(p.webSocketDebuggerUrl);
let id = 0; const pend = new Map();
ws.onmessage = e => { const m = JSON.parse(e.data); if (m.id && pend.has(m.id)) { pend.get(m.id)(m.result); pend.delete(m.id); } };
await new Promise(r => ws.onopen = r);
const send = (m, params={}) => new Promise(r => { const i=++id; pend.set(i, r); ws.send(JSON.stringify({id:i, method:m, params})); });
const ev = async (e) => { const r = await send("Runtime.evaluate", { expression: e, returnByValue: true, awaitPromise: true }); return r.result?.value ?? ('EXC ' + (r.exceptionDetails?.exception?.description||'')); };
console.log("stage children:", await ev(`JSON.stringify([...document.getElementById('stageEdit').children].map(c => c.className.split(' ')[0] + '|' + Math.round(c.getBoundingClientRect().height)))`));
console.log("params height :", await ev(`Math.round(document.querySelector('#stageEdit .params').getBoundingClientRect().height)`));
console.log("rows          :", await ev(`getComputedStyle(document.getElementById('stageEdit')).gridTemplateRows`));
ws.close();
