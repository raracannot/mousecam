const base = "http://127.0.0.1:9222";
const ts = await (await fetch(`${base}/json`)).json();
const p = ts.find(t => t.type === "page" && !t.url.startsWith("devtools://"));
const ws = new WebSocket(p.webSocketDebuggerUrl);
let id = 0; const pend = new Map();
ws.onmessage = e => { const m = JSON.parse(e.data); if (m.id && pend.has(m.id)) { pend.get(m.id)(m.result); pend.delete(m.id); } };
await new Promise(r => ws.onopen = r);
const send = (m, p={}) => new Promise(r => { const i=++id; pend.set(i, r); ws.send(JSON.stringify({id:i, method:m, params:p})); });
const ev = async (e) => { const r = await send("Runtime.evaluate", {expression:e, returnByValue:true, awaitPromise:true}); if (r.exceptionDetails) throw new Error(r.exceptionDetails.text); return r.result?.value; };
console.log("clips seen:", await ev(`window.__mc.clips.length`));
console.log("start:", await ev(`window.__TAURI__.core.invoke('record_start', { edit: '', monitor: 0, hw: false })`));
await new Promise(r => setTimeout(r, 3000));
console.log("stop :", await ev(`window.__TAURI__.core.invoke('record_stop')`));
ws.close();
