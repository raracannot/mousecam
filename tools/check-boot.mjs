const base = "http://127.0.0.1:9222";
const ts = await (await fetch(`${base}/json`)).json();
const p = ts.find(t => t.type === "page" && !t.url.startsWith("devtools://"));
const ws = new WebSocket(p.webSocketDebuggerUrl);
let id = 0; const pend = new Map();
ws.onmessage = e => { const m = JSON.parse(e.data); if (m.id && pend.has(m.id)) { pend.get(m.id)(m.result); pend.delete(m.id); } };
await new Promise(r => ws.onopen = r);
const send = (m, p={}) => new Promise(r => { const i=++id; pend.set(i, r); ws.send(JSON.stringify({id:i, method:m, params:p})); });
const ev = async (e) => { const r = await send("Runtime.evaluate", {expression:e, returnByValue:true, awaitPromise:true}); return r.result?.value ?? ('EXC ' + (r.exceptionDetails?.text||'')); };
console.log("boot ok:", await ev(`typeof window.__mc === 'object'`));
console.log("clips:", await ev(`window.__mc.clips.length`));
console.log("settings loaded:", await ev(`JSON.stringify(window.__mc.appSettings)`));
console.log("settings button:", await ev(`!!document.getElementById('wbSettings')`));
await ev(`document.getElementById('wbSettings').click()`);
await new Promise(r => setTimeout(r, 800));
console.log("dialog opens:", await ev(`!document.getElementById('settingsModal').classList.contains('is-hidden')`));
console.log("verbose checkbox:", await ev(`!!document.getElementById('setVerbose') && document.getElementById('setVerbose').checked`));
await ev(`document.getElementById('setCancel').click()`);
ws.close();
