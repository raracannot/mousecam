const base = "http://127.0.0.1:9222";
const ts = await (await fetch(`${base}/json`)).json();
const p = ts.find(t => t.type === "page" && !t.url.startsWith("devtools://"));
const ws = new WebSocket(p.webSocketDebuggerUrl);
let id = 0; const pend = new Map();
ws.onmessage = e => { const m = JSON.parse(e.data); if (m.id && pend.has(m.id)) { pend.get(m.id)(m.result); pend.delete(m.id); } };
await new Promise(r => ws.onopen = r);
const send = (m, p={}) => new Promise(r => { const i=++id; pend.set(i, r); ws.send(JSON.stringify({id:i, method:m, params:p})); });
const ev = async (e) => { const r = await send("Runtime.evaluate", {expression:e, returnByValue:true, awaitPromise:true}); if (r.exceptionDetails) return 'EXC ' + (r.exceptionDetails.exception?.description || r.exceptionDetails.text); return r.result?.value; };
await ev(`document.querySelector('.tab[data-tab="edit"]').click()`);
await new Promise(r => setTimeout(r, 2200));
console.log("video ready:", await ev(`(() => { const v = document.getElementById('viewVideo'); return v.readyState + ' / ' + v.videoWidth + 'x' + v.videoHeight; })()`));
console.log("canvas tainted?", await ev(`(() => { const c = document.getElementById('cropCanvas');
  try { c.getContext('2d').getImageData(0,0,1,1); return 'NO (clean)'; } catch (e) { return 'YES: ' + e.name; } })()`));
ws.close();
