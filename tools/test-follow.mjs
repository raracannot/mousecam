const base = "http://127.0.0.1:9222";
const ts = await (await fetch(`${base}/json`)).json();
const p = ts.find(t => t.type === "page" && !t.url.startsWith("devtools://"));
const ws = new WebSocket(p.webSocketDebuggerUrl);
let id = 0; const pend = new Map();
ws.onmessage = e => { const m = JSON.parse(e.data); if (m.id && pend.has(m.id)) { pend.get(m.id)(m.result); pend.delete(m.id); } };
await new Promise(r => ws.onopen = r);
const send = (m, p={}) => new Promise(r => { const i=++id; pend.set(i, r); ws.send(JSON.stringify({id:i, method:m, params:p})); });
const ev = async (e) => { const r = await send("Runtime.evaluate", {expression:e, returnByValue:true, awaitPromise:true}); return r.result?.value ?? ('EXC ' + (r.exceptionDetails?.text||'')); };
await ev(`document.querySelector('.tab[data-tab="edit"]').click()`);
await new Promise(r => setTimeout(r, 2000));
const before = await ev(`JSON.stringify({ proxy: window.__mc.proxyReady, useVideo: window.__mc.useVideo, frame: window.__mc.frame })`);
console.log("state:", before);
// play and sample the right canvas twice
await ev(`document.getElementById('btnPlay').click()`);
await new Promise(r => setTimeout(r, 900));
const a = await ev(`document.getElementById('cropCanvas').toDataURL().length`);
const fa = await ev(`window.__mc.frame`);
await new Promise(r => setTimeout(r, 900));
const b = await ev(`document.getElementById('cropCanvas').toDataURL().length`);
const fb = await ev(`window.__mc.frame`);
await ev(`document.getElementById('btnPlay').click()`);
console.log("frames:", fa, "->", fb, "| crop canvas bytes:", a, "->", b, "| changing:", a !== b);
ws.close();
